package com.swufe.homework.ui.theme

import androidx.compose.ui.unit.dp

/**
 * 间距只用这五档：
 * - xs 4：图标与文字、标签内边距
 * - sm 8：同一组内的元素（卡片里的行、标签之间）
 * - md 12：列表项之间、卡片内边距（紧凑）
 * - lg 16：页面左右边距、卡片内边距、分组之间
 * - xl 24：大区块之间、空状态四周、表单页左右边距
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
}
